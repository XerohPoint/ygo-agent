"""Deck registry and generated code list for the Edison learner.

The registry names 3 fixtures (unchanged assets) and 18 gauntlet lists, prefixed
"g_" because two gauntlet stems collide with fixture stems. Two gauntlet lists hold
XX-Saber Gottoms, which is legal now but absent from code list v1. Those are played with
that card removed, in a generated copy under build/. Sources stay unedited.

The Side Deck is dropped from generated copies only when a copy is needed; production
parses and discards it in every case.
"""
import hashlib
import json
import os
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DB = ROOT / "assets/locale/en/cards.cdb"
SCRIPTS = Path(os.environ.get("EDISON_SCRIPTS", "/home/mada/ygopro-scripts"))
LEGALITY = ROOT / "assets/edison/legality.json"
GAUNTLET = ROOT / "assets/edison/gauntlet_candidates"
CODES = Path(__file__).resolve().parent / "codes_v1.txt"
CODES_META = Path(__file__).resolve().parent / "codes_v1.json"
GENERATED = ROOT / "build/edison-learner-2026-11-04/decks"

FIXTURES = {"blackwing": ROOT / "assets/edison/decks/blackwing.ydk",
            "frog_monarch": ROOT / "assets/edison/decks/frog_monarch.ydk",
            "machina_gadget": ROOT / "assets/edison/agent_decks/machina_gadget.ydk"}
FIXTURE_NAMES = tuple(FIXTURES)

TYPE_NORMAL, TYPE_TOKEN, TYPE_PENDULUM = 0x10, 0x4000, 0x1000000
ARTWORK_OFFSET = 20
OUTSIDE_V1 = {52352005}  # XX-Saber Gottoms. A list that includes it needs a new code list and new checkpoints.


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def parse_ydk(text):
    zones, zone = {"main": [], "extra": [], "side": []}, None
    for line in text.splitlines():
        line = line.strip()
        if line == "#main":
            zone = "main"
        elif line == "#extra":
            zone = "extra"
        elif line == "!side":
            zone = "side"
        elif line.isdigit():
            zones[zone].append(int(line))
    return zones


def write_ydk(path, zones):
    lines = ["#generated by tools/edison/learner/decks.py", "#main"]
    lines += [str(c) for c in zones["main"]]
    lines += ["#extra"] + [str(c) for c in zones["extra"]]
    lines += ["!side"] + [str(c) for c in zones["side"]]
    Path(path).write_text("\n".join(lines) + "\n")


def pool_ids():
    return {code for card in json.loads(LEGALITY.read_text())["cards"] for code in card["accepted_ids"]}


def gauntlet_names():
    return tuple(d["name"] for d in json.loads((GAUNTLET / "manifest.json").read_text())["decks"])


def registry():
    """Name to .ydk path for all 21 lists. Writes the two filtered copies when absent."""
    decks = {name: path for name, path in FIXTURES.items()}
    pool = pool_ids()
    for name in gauntlet_names():
        source = GAUNTLET / f"{name}.ydk"
        zones = parse_ydk(source.read_text())
        outside = [c for zone in zones.values() for c in zone if c not in pool or c in OUTSIDE_V1]
        if outside:
            filtered = {zone: [c for c in codes if c in pool and c not in OUTSIDE_V1] for zone, codes in zones.items()}
            GENERATED.mkdir(parents=True, exist_ok=True)
            path = GENERATED / f"g_{name}.ydk"
            # Concurrent workers may race here, so publish atomically.
            scratch = path.with_suffix(f".{os.getpid()}.tmp")
            write_ydk(scratch, filtered)
            os.replace(scratch, path)
            decks[f"g_{name}"] = path
        else:
            decks[f"g_{name}"] = source
    return decks


def is_artwork(code, alias):
    return bool(alias) and alias < code + ARTWORK_OFFSET and code < alias + ARTWORK_OFFSET


def needs_script(card_type):
    return not (card_type & TYPE_NORMAL) or bool(card_type & TYPE_PENDULUM)


def build_closure():
    """Every code a duel between registry decks can ask the native module for.

    Starts from every Main, Extra and Side card. Adds all database tokens, because
    scripts often compute token ids rather than spell them, and then adds alias bases
    and numeric references in scripts until nothing changes.
    """
    decks = registry()
    db = sqlite3.connect(DB)
    rows = {r[0]: (r[1], r[2]) for r in db.execute("select id,alias,type from datas")}
    named = {r[0] for r in db.execute("select id from texts")}
    seeds = {}
    for name, path in decks.items():
        # Include removed Gottoms only through the filtered copy: it never reaches a duel.
        for zone in parse_ydk(Path(path).read_text()).values():
            for code in zone:
                seeds.setdefault(code, set()).add(f"deck:{name}")
    tokens = [c for c, (_, kind) in rows.items() if kind & TYPE_TOKEN]
    reasons = {code: set(why) for code, why in seeds.items()}
    for code in tokens:
        reasons.setdefault(code, set()).add("database token")
    frontier = list(reasons)
    while frontier:
        code = frontier.pop()
        if code not in rows:
            raise ValueError(f"Card {code} is missing from the database")
        alias, kind = rows[code]
        if alias and alias not in reasons:
            reasons[alias] = {f"alias of {code}"}
            frontier.append(alias)
        script = SCRIPTS / f"c{alias if is_artwork(code, alias) else code}.lua"
        if script.exists():
            for number in set(re.findall(r"\b(\d{5,9})\b", script.read_text(errors="replace"))):
                number = int(number)
                if number in rows and number not in reasons:
                    reasons[number] = {f"referenced by c{code}"}
                    frontier.append(number)
    missing_text = sorted(code for code in reasons if code not in named)
    if missing_text:
        raise ValueError(f"Cards with no text row: {missing_text[:5]}")
    return {code: sorted(why) for code, why in sorted(reasons.items())}, rows


def write_codelist():
    closure, rows = build_closure()
    decks = registry()
    lines = [f"{code} {1 if needs_script(rows[code][1]) else 0}" for code in closure]
    CODES.write_text("\n".join(lines) + "\n")
    meta = {"format": "edison_learner_codes_v1",
            "note": "Line number is the card id. Never edit in place: a new pool gets a new list "
                    "and checkpoints fail closed on a hash mismatch.",
            "codes": len(lines), "sha256": digest(CODES),
            "from_decks": sum(any(w.startswith("deck:") for w in why) for why in closure.values()),
            "tokens": sum("database token" in why for why in closure.values()),
            "other_closure": sum(not any(w.startswith("deck:") or w == "database token" for w in why)
                                 for why in closure.values()),
            "scripts_sha": "see tests/edison/assets.lock.json for pinned scripts",
            "decks": {name: {"path": str(Path(path).relative_to(ROOT)), "sha256": digest(path)}
                      for name, path in decks.items()}}
    CODES_META.write_text(json.dumps(meta, indent=1) + "\n")
    return meta


def load_codes(path=CODES):
    """Return (sha256, {id: code}) and refuse a list that does not parse exactly."""
    codes = {}
    for index, line in enumerate(Path(path).read_text().splitlines(), 1):
        code, flag = line.split()
        if flag not in ("0", "1"):
            raise ValueError(f"Bad code list line {index}")
        codes[index] = int(code)
    if len(set(codes.values())) != len(codes):
        raise ValueError("Duplicate code in code list")
    return digest(path), codes


def card_metadata(path=CODES):
    """Public printed data keyed by code-list id, as agent_match.py builds it."""
    _, codes = load_codes(path)
    db = sqlite3.connect(DB)
    metadata = {}
    for cid, code in codes.items():
        row = db.execute("select name,atk,def,level from datas join texts using(id) where id=?", (code,)).fetchone()
        if row is None:
            raise ValueError(f"Card {code} has no metadata")
        name, atk, defense, level = row
        metadata[cid] = {"code": code, "name": name, "atk": atk, "def": defense, "level": level & 255}
    return metadata


