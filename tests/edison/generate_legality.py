#!/usr/bin/env python3
"""Generate the compiled Edison legality tables from the reviewed local manifest."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "assets/edison/legality.json"
HEADER = ROOT / "ygoenv/ygoenv/ygopro/edison_legality_data.h"

def render():
    data = json.loads(MANIFEST.read_text())
    ids = sorted({code for card in data["cards"] for code in card["accepted_ids"]})
    limits = sorted((card["code"], card["limit"]) for card in data["restrictions"])
    if len(limits) != 135 or len(dict(limits)) != 135:
        raise ValueError("Expected 135 distinct March 2010 restrictions")
    if {x: sum(limit == x for _, limit in limits) for x in (0, 1, 2)} != {0: 45, 1: 70, 2: 20}:
        raise ValueError("Restriction category counts differ from the reviewed source")
    lines = ["#pragma once", "// Generated by tests/edison/generate_legality.py; do not edit.",
             "#include <array>", "#include <cstdint>", "#include <utility>",
             "namespace ygopro::deck_rules::data {",
             f"inline constexpr std::array<uint32_t, {len(ids)}> pool = {{{{"]
    for offset in range(0, len(ids), 10):
        lines.append("  " + ", ".join(map(str, ids[offset:offset+10])) + ",")
    lines += ["}};", f"inline constexpr std::array<std::pair<uint32_t, uint8_t>, {len(limits)}> limits = {{{{"]
    lines += [f"  {{{code}, {limit}}}," for code, limit in limits]
    lines += ["}};", "} // namespace ygopro::deck_rules::data", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if HEADER.read_text() != expected:
            raise SystemExit("Generated legality header differs from the reviewed manifest")
        print("Legality manifest/header agreement: PASS")
    else:
        HEADER.write_text(expected)
